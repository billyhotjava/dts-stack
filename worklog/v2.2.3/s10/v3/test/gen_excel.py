"""
生成 ODS v2 测试数据 Excel 文件（纯标准库，无第三方依赖）
按 ODS 表一表一文件输出到当前目录。
"""

import zipfile, xml.etree.ElementTree as ET, os, io
from datetime import date, timedelta

OUT_DIR = os.path.dirname(os.path.abspath(__file__))

# ─── minimal xlsx writer (pure stdlib) ───────────────────────
def _col_letter(idx):
    """0-based column index → Excel column letter (A, B, ..., Z, AA, ...)"""
    r = ""
    while True:
        r = chr(65 + idx % 26) + r
        idx = idx // 26 - 1
        if idx < 0:
            break
    return r

def _make_shared_strings(strings):
    root = ET.Element("sst", xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main",
                       count=str(len(strings)), uniqueCount=str(len(strings)))
    for s in strings:
        si = ET.SubElement(root, "si")
        t = ET.SubElement(si, "t")
        t.text = str(s) if s is not None else ""
    return ET.tostring(root, encoding="unicode", xml_declaration=True)

def _make_sheet(rows, shared_idx):
    root = ET.Element("worksheet", xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main")
    sd = ET.SubElement(root, "sheetData")
    for ri, row in enumerate(rows, 1):
        r_el = ET.SubElement(sd, "row", r=str(ri))
        for ci, val in enumerate(row):
            ref = f"{_col_letter(ci)}{ri}"
            c = ET.SubElement(r_el, "c", r=ref, t="s")
            v = ET.SubElement(c, "v")
            v.text = str(shared_idx[(ri - 1, ci)])
    return ET.tostring(root, encoding="unicode", xml_declaration=True)

def write_xlsx(filepath, sheets_data):
    """
    sheets_data: dict of {sheet_name: [headers_list, row1_list, row2_list, ...]}
    """
    # collect all unique strings
    all_strings = []
    str_to_idx = {}
    cell_idx = {}  # (sheet, row, col) → idx in shared strings

    for sheet_name, rows in sheets_data.items():
        for ri, row in enumerate(rows):
            for ci, val in enumerate(row):
                s = str(val) if val is not None else ""
                if s not in str_to_idx:
                    str_to_idx[s] = len(all_strings)
                    all_strings.append(s)
                cell_idx[(sheet_name, ri, ci)] = str_to_idx[s]

    with zipfile.ZipFile(filepath, "w", zipfile.ZIP_DEFLATED) as zf:
        # [Content_Types].xml
        ct = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
              '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
              '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
              '<Default Extension="xml" ContentType="application/xml"/>'
              '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
              '<Override PartName="/xl/sharedStrings.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sharedStrings+xml"/>')
        for i in range(len(sheets_data)):
            ct += f'<Override PartName="/xl/worksheets/sheet{i+1}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
        ct += '</Types>'
        zf.writestr("[Content_Types].xml", ct)

        # _rels/.rels
        zf.writestr("_rels/.rels",
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>'
            '</Relationships>')

        # xl/_rels/workbook.xml.rels
        rels = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                '<Relationship Id="rIdSS" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/sharedStrings" Target="sharedStrings.xml"/>')
        for i in range(len(sheets_data)):
            rels += f'<Relationship Id="rId{i+1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet{i+1}.xml"/>'
        rels += '</Relationships>'
        zf.writestr("xl/_rels/workbook.xml.rels", rels)

        # xl/workbook.xml
        wb = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
              '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
              'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
              '<sheets>')
        for i, name in enumerate(sheets_data.keys()):
            wb += f'<sheet name="{name}" sheetId="{i+1}" r:id="rId{i+1}"/>'
        wb += '</sheets></workbook>'
        zf.writestr("xl/workbook.xml", wb)

        # xl/sharedStrings.xml
        zf.writestr("xl/sharedStrings.xml", _make_shared_strings(all_strings))

        # xl/worksheets/sheet{n}.xml
        for i, (sheet_name, rows) in enumerate(sheets_data.items()):
            per_sheet_idx = {}
            for ri, row in enumerate(rows):
                for ci, val in enumerate(row):
                    per_sheet_idx[(ri, ci)] = cell_idx[(sheet_name, ri, ci)]
            zf.writestr(f"xl/worksheets/sheet{i+1}.xml", _make_sheet(rows, per_sheet_idx))

    print(f"  -> {filepath} ({len(sheets_data)} sheet(s))")


