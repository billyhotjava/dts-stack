-- ============================================================
-- 卡片名称：资金流动瀑布图
-- 用途：展示年初 -> +增加 -> -使用 -> 年末余额 的资金流向
-- 所属大屏：F4 自有资金大屏
-- 数据表：biz_dws_own_fund_yearly（DWS 层）
-- ============================================================

SELECT
    opening_total,              -- 年初合计（万元，瀑布图第一根柱）
    increase_total,             -- 预计增加（万元，瀑布图第二根柱，绿色向上）
    usage_total,                -- 预计使用（万元，瀑布图第三根柱，红色向下）
    balance_total               -- 年末余额（万元，瀑布图第四根柱，最终结果）
FROM biz_dws_own_fund_yearly
WHERE period_year = :selected_year;
