    total_balance,              -- 余额合计（单位：元，前端转万元显示）
    subject_count,              -- 涉及科目数（去重）
    contract_count,             -- 有效合同数（去重，排除 NULL 和 '—'）
    dept_count                  -- 涉及部门数（去重）
FROM biz_ads_aux_balance_kpi;
